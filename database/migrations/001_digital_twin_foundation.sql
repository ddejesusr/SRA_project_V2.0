-- -----------------------------------------------------------------------------
-- Festo CP Lab process-state catalog
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS festo_state_codes (
    state_code INTEGER PRIMARY KEY,
    process_state VARCHAR(64) NOT NULL UNIQUE,
    top_cover VARCHAR(8),
    description TEXT NOT NULL,
    CHECK (top_cover IS NULL OR top_cover IN ('blue', 'red'))
);

